"""PostgreSQL schema for shared history and backtest evidence."""

from __future__ import annotations

import psycopg


def migrate(db: psycopg.Connection) -> None:
    """Create the backtest schema within the caller's migration transaction."""
    db.execute("""
        CREATE TABLE IF NOT EXISTS shared_bars (
            symbol TEXT NOT NULL, interval_minutes INTEGER NOT NULL,
            timestamp TEXT NOT NULL, bar_json TEXT NOT NULL,
            PRIMARY KEY (symbol, interval_minutes, timestamp)
        )
    """)
    db.execute("""
        CREATE TABLE IF NOT EXISTS shared_history_ranges (
            symbol TEXT NOT NULL, interval_minutes INTEGER NOT NULL,
            start_date TEXT NOT NULL, end_date TEXT NOT NULL,
            PRIMARY KEY (symbol, interval_minutes, start_date, end_date)
        )
    """)
    db.execute("""
        CREATE TABLE IF NOT EXISTS minute_snapshots (
            snapshot_id TEXT PRIMARY KEY, bars_json TEXT NOT NULL
        )
    """)
    db.execute("""
        CREATE TABLE IF NOT EXISTS backtests (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            snapshot_id TEXT NOT NULL REFERENCES minute_snapshots(snapshot_id),
            result_json TEXT NOT NULL
        )
    """)
    db.execute("""
        CREATE TABLE IF NOT EXISTS shared_daily_bars (
            symbol TEXT NOT NULL, timestamp TEXT NOT NULL, bar_json TEXT NOT NULL,
            PRIMARY KEY (symbol, timestamp)
        )
    """)
    db.execute("""
        CREATE TABLE IF NOT EXISTS shared_daily_history_ranges (
            symbol TEXT NOT NULL, start_date TEXT NOT NULL, end_date TEXT NOT NULL,
            PRIMARY KEY (symbol, start_date, end_date)
        )
    """)


def migrate_daily_trading_date(db: psycopg.Connection) -> None:
    """Make the shared daily key match its symbol/trading-date identity."""
    db.execute(
        "ALTER TABLE shared_daily_bars ADD COLUMN IF NOT EXISTS trading_date TEXT"
    )
    db.execute(
        "UPDATE shared_daily_bars SET trading_date=left(timestamp, 10) "
        "WHERE trading_date IS NULL"
    )
    db.execute("""
        DELETE FROM shared_daily_bars
        WHERE ctid IN (
            SELECT ctid FROM (
                SELECT ctid, row_number() OVER (
                    PARTITION BY symbol, trading_date ORDER BY timestamp DESC
                ) AS position
                FROM shared_daily_bars
            ) ranked WHERE position > 1
        )
    """)
    db.execute(
        "ALTER TABLE shared_daily_bars ALTER COLUMN trading_date SET NOT NULL"
    )
    db.execute(
        "CREATE UNIQUE INDEX IF NOT EXISTS shared_daily_bars_symbol_trading_date_idx "
        "ON shared_daily_bars (symbol, trading_date)"
    )
