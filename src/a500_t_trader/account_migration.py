"""PostgreSQL schema for account records and trade imports."""

from __future__ import annotations

import psycopg


def migrate(db: psycopg.Connection) -> None:
    """Create account tables within the caller's migration transaction."""
    db.execute("""CREATE TABLE IF NOT EXISTS account_snapshots (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        as_of TEXT NOT NULL, record_json TEXT NOT NULL, classification TEXT NOT NULL
    )""")
    db.execute("""CREATE TABLE IF NOT EXISTS manual_fills (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        timestamp TEXT NOT NULL, symbol TEXT NOT NULL,
        side TEXT NOT NULL CHECK (side IN ('buy', 'sell')),
        quantity INTEGER NOT NULL CHECK (quantity > 0), price TEXT NOT NULL,
        notes TEXT NOT NULL, classification TEXT NOT NULL
    )""")
    db.execute("""CREATE TABLE IF NOT EXISTS imported_fills (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        owner TEXT, timestamp TEXT NOT NULL, symbol TEXT NOT NULL,
        side TEXT NOT NULL CHECK (side IN ('buy', 'sell')),
        quantity INTEGER NOT NULL CHECK (quantity > 0), price TEXT NOT NULL,
        trade_amount TEXT NOT NULL, fees TEXT NOT NULL, stamp_duty TEXT NOT NULL,
        other_charges TEXT NOT NULL, occurrence_amount TEXT NOT NULL,
        source TEXT NOT NULL, trade_number TEXT NOT NULL,
        contract_number TEXT NOT NULL, classification TEXT NOT NULL
    )""")
    db.execute("""CREATE UNIQUE INDEX IF NOT EXISTS imported_fills_owner_trade
        ON imported_fills (COALESCE(owner, ''), source, trade_number)""")
    db.execute("""CREATE TABLE IF NOT EXISTS account_snapshot_current (
        subject TEXT PRIMARY KEY, snapshot_json TEXT NOT NULL, updated_at TEXT NOT NULL
    )""")
    db.execute("""CREATE TABLE IF NOT EXISTS account_snapshot_history (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        subject TEXT NOT NULL, snapshot_json TEXT NOT NULL, as_of TEXT NOT NULL,
        updated_at TEXT NOT NULL, classification TEXT NOT NULL
    )""")
    db.execute("""CREATE TABLE IF NOT EXISTS trade_import_batches (
        batch_id TEXT PRIMARY KEY, owner TEXT NOT NULL, records_json TEXT NOT NULL,
        errors_json TEXT NOT NULL, summary_json TEXT NOT NULL,
        created_at DOUBLE PRECISION NOT NULL, expires_at DOUBLE PRECISION NOT NULL,
        confirmed_json TEXT
    )""")
